# ─── 스타일 ─────────────────────────────────────────────────────────
FONT_NAME = "맑은 고딕"
HEADER_FILL = PatternFill("solid", fgColor="BFBFBF")
GROUP_FILL  = PatternFill("solid", fgColor="D9D9D9")
MENU_FILL   = PatternFill("solid", fgColor="F2F2F2")

thin = Side(border_style="thin", color="808080")
BORDER = Border(left=thin, right=thin, top=thin, bottom=thin)

header_font = Font(name=FONT_NAME, size=11, bold=True, color="000000")
group_font  = Font(name=FONT_NAME, size=10, bold=True, color="000000")
menu_font   = Font(name=FONT_NAME, size=10, bold=True, color="000000")
body_font   = Font(name=FONT_NAME, size=10, color="000000")

center_align = Alignment(horizontal="center", vertical="center", wrap_text=True)
left_align   = Alignment(horizontal="left",   vertical="center", wrap_text=True)
top_align    = Alignment(horizontal="left",   vertical="top",    wrap_text=True)
menu_align   = Alignment(horizontal="center", vertical="center", wrap_text=True)

# ─── 워크북 작성 ─────────────────────────────────────────────────────
wb = Workbook()
ws = wb.active
ws.title = "TA 기능 정의서"

ws.column_dimensions["A"].width = 24
ws.column_dimensions["B"].width = 110

ws.cell(row=1, column=1, value="구분").font = header_font
ws.cell(row=1, column=2, value="내용").font = header_font
for col in (1, 2):
    c = ws.cell(row=1, column=col)
    c.fill = HEADER_FILL
    c.alignment = center_align
    c.border = BORDER
ws.row_dimensions[1].height = 28

row = 2
for group_name, menus in DATA:
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=2)
    cell = ws.cell(row=row, column=1, value=f"■  {group_name}")
    cell.fill = GROUP_FILL
    cell.font = group_font
    cell.alignment = left_align
    cell.border = BORDER
    ws.cell(row=row, column=2).border = BORDER
    ws.row_dimensions[row].height = 22
    row += 1

    for menu_name, description, bullets in menus:
        a = ws.cell(row=row, column=1, value=menu_name)
        a.font = menu_font
        a.fill = MENU_FILL
        a.alignment = menu_align
        a.border = BORDER

        body_text = (
            "■ 페이지 설명\n"
            f"{description}\n"
            "\n"
            "■ 주요 기능\n"
            + "\n".join(f"• {b}" for b in bullets)
        )
        b = ws.cell(row=row, column=2, value=body_text)
        b.font = body_font
        b.alignment = top_align
        b.border = BORDER

        desc_lines = description.count("\n") + 1
        total_lines = desc_lines + 1 + 1 + 1 + len(bullets)
        ws.row_dimensions[row].height = max(18 * total_lines + 10, 120)
        row += 1

ws.freeze_panes = "A2"

